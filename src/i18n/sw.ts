// Deep-merge Swahili overrides into English. Anything missing on the sw side falls
// back to the English string, so we can grow the translation surface incrementally
// without ever showing an empty label.
function deepMerge<T>(base: T, over: unknown): T {
  if (!over || typeof over !== 'object' || Array.isArray(over)) return base;
  const b = base as Record<string, unknown>;
  const o = over as Record<string, unknown>;
  const out: Record<string, unknown> = { ...b };
  for (const key of Object.keys(o)) {
    const bv = b[key];
    const ov = o[key];
    if (bv && typeof bv === 'object' && !Array.isArray(bv) && ov && typeof ov === 'object' && !Array.isArray(ov)) {
      out[key] = deepMerge(bv, ov);
    } else if (ov !== undefined) {
      out[key] = ov;
    }
  }
  return out as T;
}

export const sw = getLang() === 'sw'
  ? deepMerge(english, swahiliOverrides)
  : english;

export type SwCopy = typeof english;
